def main():
    entries = json.load(open(os.path.join(ROOT, "tools", "desc_extract.json"),
                             encoding="utf-8"))
    # Group target translations by file.
    by_file = {}
    for e in entries:
        i = e["id"]
        if i in SKIP or i not in T:
            continue
        by_file.setdefault(e["file"], {})[e["text"]] = T[i]

    total = 0
    for rel, mapping in by_file.items():
        path = os.path.join(ROOT, rel)
        with open(path, "r", encoding="utf-8") as fh:
            content = fh.read()

        def repl(m):
            joined = "".join(LIT_RE.findall(m.group(0)))
            if joined in mapping:
                return 'return "%s";' % mapping[joined]
            return m.group(0)

        new_content = RETURN_RE.sub(repl, content)
        if new_content != content:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(new_content)
            total += 1
    print("files with replaced paragraphs: %d" % total)


if __name__ == "__main__":
    sys.exit(main())
